/* FORMA: نصايح فورما.
   منطق صافي بدون واجهة: ياخذ أرقام المستخدم ويرجع نصايح مرتبة حسب الأهمية.
   الكلام باللهجة النجدية. أي نسخة (ويب أو تطبيق) تقدر تستخدم نفس الملف. */
(function () {
  "use strict";
  const r1 = n => Math.round(n * 10) / 10;
  const f0 = n => Math.round(n).toLocaleString("en-US");
  const abs = Math.abs;

  /* c: أرقام المستخدم، يجهزها app.js (شوف coachCtx) */
  function tips(c) {
    const out = [];
    const add = (id, prio, t, act) => out.push({ id, prio, t, act });
    const nm = c.name ? " يا " + c.name : "";

    /* بداية */
    if (c.daysSinceStart <= 1 && !c.anyFood) {
      add("new", 100, `هلا${nm}! أول شي: سجّل كل اللي تاكله اليوم ولو تقريبي، وبكرة الصبح اوزن نفسك. الباقي علينا.`, "food");
    }

    /* وصل هدفه أو قرّب */
    if (c.tw && c.goal !== 1 && c.cw) {
      const reached = c.goal === 0 ? c.cw <= c.tw : c.cw >= c.tw;
      if (reached) add("goal-done", 95, `وصلت هدفك ${c.tw} كغ! ألف مبروك${nm}. حط هدف جديد أو حوّل للثبات من ملفك.`, "setup");
      else if (abs(c.cw - c.tw) <= 1) add("goal-near", 76, `باقي لك أقل من كيلو وتوصل ${c.tw} كغ. قربت حيل، لا توقف الحين.`);
    }

    /* رقم قياسي قريب */
    if (c.prs3 && c.prs3.length) {
      add("pr", 90, `كفو${nm}! كسرت رقمك في ${c.prs3[0]}${c.prs3.length > 1 ? " و" + (c.prs3.length - 1) + " تمارين ثانية" : ""}. هذا يعني عضلك يقوى، كمّل وزد الوزن شوي شوي.`);
    }

    /* الوزن حسب الهدف */
    const t = c.trend;
    if (t) {
      const kg = r1(abs(t.kgWeek));
      if (c.goal === 0) {
        if (t.pct <= -1.1) add("cut-fast", 85, `نزولك سريع حيل (${kg} كغ بالأسبوع). زد أكلك 150 سعرة تقريبا عشان ما تخسر من عضلك.`);
        else if (t.pct <= -0.4) add("cut-ok", 60, `ما شاء الله، نازل ${kg} كغ بالأسبوع. هذا النزول المطلوب بالضبط، خلك على نفس الخطة.`);
        else if (t.pct < 0.15) { if (c.daysSinceStart >= 14) add("cut-slow", 75, "نزولك بطيء هالأسبوعين. شيك على الصوصات والمشروبات وأكل المطاعم، غالبا السعرات الزايدة مخبية هناك.", "food"); }
        else add("cut-up", 70, "وزنك زاد شوي بدل ما ينزل. لا تحاتي، الوزن يتذبذب مع الموية والملح. سجّل أكلك أسبوع كامل وبنعرف السالفة.", "food");
      } else if (c.goal === 2) {
        if (t.pct >= 0.6) add("bulk-fast", 85, `زيادتك سريعة (${kg} كغ بالأسبوع)، وأغلبها بيصير دهون. نقّص 150 سعرة من أكلك.`);
        else if (t.pct >= 0.1) add("bulk-ok", 60, `زيادتك ممتازة، ${kg} كغ بالأسبوع. هذي زيادة نظيفة، كمّل.`);
        else add("bulk-slow", 75, "وزنك ما تحرك. زد لقمة على كل وجبة، أو كاسة حليب قبل النوم.", "food");
      } else {
        if (t.kgWeek >= 0.4) add("keep-up", 70, `وزنك زاد ${kg} كغ هالأسبوع وهدفك الثبات. خفف السناكات شوي.`);
        else if (t.kgWeek <= -0.4) add("keep-down", 70, `وزنك نقص ${kg} كغ هالأسبوع وهدفك الثبات. زد أكلك شوي.`);
        else add("keep-ok", 50, "وزنك ثابت زي ما تبي. ركّز على التمرين وزيادة الأوزان.");
      }
    }

    /* البروتين */
    if (c.log7 >= 3 && c.avgP7 != null) {
      if (c.avgP7 < 0.8 * c.prot) add("prot-low", 80, `بروتينك هالأسبوع ${f0(c.avgP7)} جم بالمتوسط، وهدفك ${c.prot}. زد البيض والدجاج والزبادي، ترى العضل ما ينبني بدونه.`);
      else if (c.avgP7 >= 0.95 * c.prot && c.log7 >= 4) add("prot-ok", 40, `بروتينك مضبوط هالأسبوع، متوسطك ${f0(c.avgP7)} جم. هذا اللي يحافظ على عضلك.`);
    }

    /* السعرات */
    if (c.log7 >= 3 && c.avgK7 != null) {
      const d = c.avgK7 - c.kcal;
      if (c.goal === 0 && d > c.kcal * 0.1) add("kcal-over", 78, `آخر أيام وأنت فوق سعراتك بـ${f0(d)} سعرة بالمتوسط. ما يحتاج تحرم نفسك، بس خفف من المطاعم والحلا.`);
      if (c.goal === 2 && -d > c.kcal * 0.1) add("kcal-under", 78, `أكلك أقل من هدفك بـ${f0(-d)} سعرة بالمتوسط. التضخيم يبي أكل كافي، زد وجبة صغيرة.`, "food");
    }

    /* التمرين */
    if (c.daysSinceTrain >= 5 && c.daysSinceTrain < 999) add("train-gap", 82, `صار لك ${c.daysSinceTrain} أيام ما تمرنت. ارجع اليوم ولو بتمرين خفيف، أهم شي ما تقطع.`, "train");
    else if (c.daysSinceTrain >= 999 && c.daysSinceStart >= 2) add("train-none", 72, `ما سجلت ولا تمرين للحين. ابدأ بـ${c.next}، وخذ أوزان مريحة أول أسبوع.`, "train");
    if (c.trainedToday) add("train-today", 45, "الله يعطيك العافية على تمرين اليوم. كل وجبة فيها بروتين زين عشان عضلك يستفيد.");
    else if (c.week.done >= c.week.plan && c.week.plan > 0) add("train-week", 55, `خلصت تمارينك هالأسبوع (${c.week.done} من ${c.week.plan}). يا زينك! ارتاح ونام كفاية.`);

    /* الوزن اليومي */
    if (c.lastWeighDays >= 4 && c.lastWeighDays < 999) add("weigh", 65, `ما وزنت نفسك من ${c.lastWeighDays} أيام. اوزن الصبح قبل الأكل، عشان FORMA يضبط سعراتك صح.`, "weight");

    /* التسجيل */
    if (c.hour >= 15 && !c.todayLogged && c.anyFood) add("log-today", 68, "ما سجلت أكل اليوم للحين. سجّل ولو تقريبي، أحسن من لا شي.", "food");
    if (c.daysSinceStart >= 5 && c.log7 <= 2) add("log-week", 66, `سجلك هالأسبوع قليل (${c.log7} ${c.log7 === 1 ? "يوم" : "أيام"}). الأرقام ما تصدق إلا إذا سجلت أغلب الأيام.`, "food");
    if (c.hour >= 18 && c.todayLogged && c.prot - c.todayP >= 40) add("prot-left", 62, `باقي لك ${f0(c.prot - c.todayP)} جم بروتين اليوم. علبة زبادي يوناني أو صدر دجاج تقفلها.`, "food");

    /* السلسلة */
    if ([3, 7, 14, 21, 30, 50, 75, 100].includes(c.streak)) add("streak", 58, `${c.streak} يوم ورا بعض! الاستمرار هو السر، لا تكسر السلسلة.`);

    /* نصايح عامة تتغير كل يوم */
    const gen = [
      "النوم 7 ساعات يفرق في عضلك ونزولك أكثر مما تتوقع.",
      "اشرب موية قبل الوجبة، تشبعك وتخفف أكلك بدون ما تحس.",
      "المشي 8 آلاف خطوة باليوم يحرق زيادة بدون ما يأثر على تمرينك.",
      "الصوصات والمشروبات تزيد سعراتك بسرعة. خذها دايت أو على جنب.",
      "في التمرين، زد الوزن أو العدات شوي كل أسبوع. هذا اللي يبني العضل.",
      "إذا طلعت مطعم، اختر المشوي بدل المقلي، والسلطة بدل البطاطس.",
      "يوم خربت فيه أكلك؟ عادي. لا تعوضه بالجوع، ارجع لخطتك من الوجبة الجاية.",
      "البروتين في كل وجبة يشبعك أطول ويحافظ على عضلك.",
      "لا تقارن وزن يوم بيوم. شوف متوسط الأسبوع، هو اللي يعطيك الصورة الصح.",
    ];
    add("gen", 10, gen[(c.dayNum || 0) % gen.length]);

    out.sort((a, b) => b.prio - a.prio);
    return out;
  }

  window.FORMA_COACH = { tips };
})();
