/* FORMA: نصايح فورما.
   منطق صافي بدون واجهة: ياخذ أرقام المستخدم ويرجع نصايح مرتبة حسب الأهمية.
   الأسلوب: عربي واضح ومهني بلمسة سعودية خفيفة. أي نسخة (ويب أو تطبيق) تستخدم نفس الملف. */
(function () {
  "use strict";
  const r1 = n => Math.round(n * 10) / 10;
  const f0 = n => Math.round(n).toLocaleString("en-US");
  const abs = Math.abs;

  /* c: أرقام المستخدم، يجهزها app.js (شوف coachCtx) */
  function tips(c) {
    const out = [];
    const add = (id, prio, t, act) => out.push({ id, prio, t, act });
    const nm = c.name ? " يا " + c.name : "";

    /* بداية */
    if (c.daysSinceStart <= 1 && !c.anyFood) {
      add("new", 100, `أهلا${nm}. ابدأ بتسجيل كل ما تأكله اليوم ولو بشكل تقريبي، وسجّل وزنك بكرة الصبح قبل الأكل.`, "food");
    }

    /* وصل هدفه أو قرّب */
    if (c.tw && c.goal !== 1 && c.cw) {
      const reached = c.goal === 0 ? c.cw <= c.tw : c.cw >= c.tw;
      if (reached) add("goal-done", 95, `وصلت لهدفك ${c.tw} كغ. مبروك${nm}. حدد هدف جديد أو حوّل للثبات من ملفك.`, "setup");
      else if (abs(c.cw - c.tw) <= 1) add("goal-near", 76, `باقي أقل من كيلو على هدفك ${c.tw} كغ. استمر على نفس الخطة.`);
    }

    /* رقم قياسي قريب */
    if (c.prs3 && c.prs3.length) {
      add("pr", 90, `سجّلت رقم قياسي جديد في ${c.prs3[0]}${c.prs3.length === 2 ? " وتمرين آخر" : c.prs3.length === 3 ? " وتمرينين آخرين" : c.prs3.length > 3 ? " و" + (c.prs3.length - 1) + " تمارين أخرى" : ""}. قوتك تتحسن، استمر وزد الوزن بالتدريج.`);
    }

    /* الوزن حسب الهدف */
    const t = c.trend;
    if (t) {
      const kg = r1(abs(t.kgWeek));
      if (c.goal === 0) {
        if (t.pct <= -1.1) add("cut-fast", 85, `نزولك سريع (${kg} كغ بالأسبوع). زد أكلك 150 سعرة تقريبا عشان تحافظ على عضلك.`);
        else if (t.pct <= -0.4) add("cut-ok", 60, `نازل ${kg} كغ بالأسبوع، وهذا المعدل المثالي. استمر على نفس الخطة.`);
        else if (t.pct < 0.15) { if (c.daysSinceStart >= 14) add("cut-slow", 75, "نزولك بطيء آخر أسبوعين. راجع الصوصات والمشروبات وأكل المطاعم، غالبا فيها السعرات الزايدة.", "food"); }
        else add("cut-up", 70, "وزنك ارتفع قليلا بدل ما ينزل. هذا طبيعي بسبب الماء والملح. سجّل أكلك أسبوع كامل عشان تتضح الصورة.", "food");
      } else if (c.goal === 2) {
        if (t.pct >= 0.6) add("bulk-fast", 85, `زيادتك سريعة (${kg} كغ بالأسبوع)، وأغلبها بيكون دهون. قلل أكلك 150 سعرة.`);
        else if (t.pct >= 0.1) add("bulk-ok", 60, `زيادتك ${kg} كغ بالأسبوع، وهذا معدل ممتاز لبناء العضل. استمر.`);
        else add("bulk-slow", 75, "وزنك ما تغيّر. زد كمية الأكل شوي في كل وجبة، أو أضف كوب حليب قبل النوم.", "food");
      } else {
        if (t.kgWeek >= 0.4) add("keep-up", 70, `وزنك زاد ${kg} كغ هالأسبوع وهدفك الثبات. قلل السناكات.`);
        else if (t.kgWeek <= -0.4) add("keep-down", 70, `وزنك نقص ${kg} كغ هالأسبوع وهدفك الثبات. زد أكلك شوي.`);
        else add("keep-ok", 50, "وزنك ثابت مثل ما تبي. ركّز على التمرين وزيادة الأوزان.");
      }
    }

    /* البروتين */
    if (c.log7 >= 3 && c.avgP7 != null) {
      if (c.avgP7 < 0.8 * c.prot) add("prot-low", 80, `متوسط بروتينك هالأسبوع ${f0(c.avgP7)} جم وهدفك ${c.prot}. زد البيض والدجاج والزبادي، فالبروتين أساس بناء العضل.`);
      else if (c.avgP7 >= 0.95 * c.prot && c.log7 >= 4) add("prot-ok", 40, `بروتينك ممتاز هالأسبوع، متوسطك ${f0(c.avgP7)} جم. هذا اللي يحافظ على عضلك.`);
    }

    /* السعرات */
    if (c.log7 >= 3 && c.avgK7 != null) {
      const d = c.avgK7 - c.kcal;
      if (c.goal === 0 && d > c.kcal * 0.1) add("kcal-over", 78, `متوسط أكلك آخر أيام أعلى من هدفك بـ${f0(d)} سعرة. قلل وجبات المطاعم والحلويات.`);
      if (c.goal === 2 && -d > c.kcal * 0.1) add("kcal-under", 78, `متوسط أكلك أقل من هدفك بـ${f0(-d)} سعرة. بناء العضل يحتاج أكل كافي، أضف وجبة صغيرة.`, "food");
    }

    /* التمرين */
    if (c.daysSinceTrain >= 5 && c.daysSinceTrain < 999) add("train-gap", 82, `مر ${c.daysSinceTrain} أيام من آخر تمرين. ارجع اليوم ولو بتمرين خفيف، فالاستمرار أهم من الشدة.`, "train");
    else if (c.daysSinceTrain >= 999 && c.daysSinceStart >= 2) add("train-none", 72, `ما سجّلت أي تمرين للحين. ابدأ بـ${c.next}، واختر أوزان مريحة في أول أسبوع.`, "train");
    if (c.trainedToday) add("train-today", 45, "أحسنت على تمرين اليوم. احرص إن وجبتك الجاية فيها بروتين كافي عشان عضلك يستفيد.");
    else if (c.week.done >= c.week.plan && c.week.plan > 0) add("train-week", 55, `أكملت تمارين هالأسبوع (${c.week.done} من ${c.week.plan}). أحسنت. خذ راحتك ونم 7 ساعات على الأقل.`);

    /* الوزن اليومي */
    if (c.lastWeighDays >= 4 && c.lastWeighDays < 999) add("weigh", 65, `آخر وزن سجّلته قبل ${c.lastWeighDays} أيام. اوزن نفسك الصبح قبل الأكل عشان تكون حساباتك دقيقة.`, "weight");

    /* التسجيل */
    if (c.hour >= 15 && !c.todayLogged && c.anyFood) add("log-today", 68, "ما سجّلت أكل اليوم. سجّله ولو بشكل تقريبي.", "food");
    if (c.daysSinceStart >= 5 && c.log7 <= 2) add("log-week", 66, `سجّلت أكلك ${c.log7} ${c.log7 === 1 ? "يوم" : "أيام"} فقط هالأسبوع. كل ما زاد التسجيل صارت الأرقام أدق.`, "food");
    if (c.hour >= 18 && c.todayLogged && c.prot - c.todayP >= 40) add("prot-left", 62, `باقي لك ${f0(c.prot - c.todayP)} جم بروتين اليوم. علبة زبادي يوناني أو صدر دجاج تكفي.`, "food");

    /* السلسلة */
    if ([3, 7, 14, 21, 30, 50, 75, 100].includes(c.streak)) add("streak", 58, `${c.streak} يوم متواصل. استمر، فالالتزام هو اللي يصنع النتيجة.`);

    /* نصايح عامة تتغير كل يوم */
    const gen = [
      "النوم 7 ساعات على الأقل يساعد على بناء العضل وخسارة الدهون.",
      "اشرب ماء قبل الوجبة، يساعدك تشبع بكمية أقل.",
      "المشي 8 آلاف خطوة يوميا يزيد حرقك بدون ما يأثر على تمرينك.",
      "الصوصات والمشروبات المحلاة ترفع السعرات بسرعة. اختر المشروب الدايت، واطلب الصوص في علبة منفصلة وخذ منه القليل.",
      "زد الوزن أو العدات بالتدريج كل أسبوع. هذا أساس بناء العضل.",
      "في المطاعم، اختر المشوي بدل المقلي، والسلطة بدل البطاطس.",
      "لو زاد أكلك في يوم، لا تعوضه بالجوع. ارجع لخطتك من الوجبة الجاية.",
      "البروتين في كل وجبة يشبعك لمدة أطول ويحافظ على عضلك.",
      "لا تقارن وزنك من يوم ليوم. المتوسط الأسبوعي هو المقياس الصحيح.",
    ];
    add("gen", 10, gen[(c.dayNum || 0) % gen.length]);

    out.sort((a, b) => b.prio - a.prio);
    return out;
  }

  window.FORMA_COACH = { tips };
})();
